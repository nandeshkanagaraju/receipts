def _plan_from(body: dict[str, Any]) -> QueryPlan:
    from ..domain.types import Filter

    window = body.get("window") or {"kind": "relative", "relative": "last_month"}
    return QueryPlan(
        kind="metric",
        name=str(body.get("metric") or body.get("name") or ""),
        dimensions=tuple(body.get("dimensions") or ()),
        filters=tuple(
            Filter(
                dimension=str(f["dimension"]),
                op=str(f.get("op", "eq")),  # type: ignore[arg-type]
                values=tuple(f["values"]),
            )
            for f in (body.get("filters") or ())
        ),
        window=WindowSpec(**window),
        grain=Grain(str(body.get("grain", "NONE"))),
        limit=body.get("limit"),
        order=body.get("order"),
    )


def _metric_intent() -> Any:
    return Intent.METRIC


def _audit(
    runtime: Runtime,
    role: str,
    plan: QueryPlan,
    status: str,
    reason: str,
    *,
    plan_hash: str | None = None,
    sql_hash: str | None = None,
    rows: int | None = None,
) -> None:
    runtime.audit.append(
        AuditEvent(
            role=role,
            session_id="mcp",
            question_text=f"run_plan:{plan.name}",
            lang="en",
            status=status,
            plan_hash=plan_hash,
            sql_hash=sql_hash,
            row_count=rows,
            reason=reason,
        )
    )


